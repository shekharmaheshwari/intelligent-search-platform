"""Study B: LLM shopper agents over a real ISP catalog and the live ISP search API.

Personas are generated by code (device, budget, category interests, brand
affinity); an OpenAI model (GPT-5.4-mini) plays each persona. Search sessions send the agent's
own query to ISP's hybrid search; browse sessions open an empty-query category
listing. The agent decides clicks from the real result cards. Events are encoded
exactly as in v1 (impression row + extra positive row per click) and the same
production learner is trained on browse-only, pooled, and row-matched pooled rows.

Evaluation: held-out personas judge randomly ordered candidate sets in a browse
context (graded 0-3); policies are scored by NDCG@10 against those judgments.

Every LLM response is cached by prompt hash in data_cache/llm_cache.jsonl, so a
rerun reproduces results at no cost; the published artifact includes that cache.
"""

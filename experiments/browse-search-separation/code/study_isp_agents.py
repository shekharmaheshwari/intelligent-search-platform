DEVICES = ['Apple iPhone 17 Pro', 'Apple iPhone 17 Pro Max', 'Apple iPhone 17', 'Apple iPhone 16',
           'Apple iPhone 15', 'Samsung Galaxy S26 Ultra', 'Samsung Galaxy S26+', 'Samsung Galaxy S26',
           'Google Pixel 10']
CATEGORIES = ['cases-&-covers', 'screen-protectors', 'chargers-&-adapters', 'headphones',
              'wearable-tech', 'speakers', 'gaming', 'others']
BUDGETS = {'tight': 'usually spends under $30', 'moderate': 'happy to spend $30-$80',
           'premium': 'will pay over $100 for quality'}


def make_personas(cfg):
    rng = np.random.default_rng(cfg['persona_seed'])
    personas = []
    brands = ['apple', 'samsung', 'otterbox', 'zagg', 'mophie', 'beats', 'jbl', 'uag', 'tech21', 'pelican']
    for i in range(cfg['personas']):
        interest = rng.dirichlet(np.full(len(CATEGORIES), 0.6))
        personas.append({
            'id': i, 'device': str(rng.choice(DEVICES)), 'budget': str(rng.choice(list(BUDGETS))),
            'interests': {c: round(float(w), 3) for c, w in zip(CATEGORIES, interest)},
            'brands': [str(b) for b in rng.choice(brands, int(rng.integers(0, 3)), replace=False)],
            'style': str(rng.choice(['practical', 'style-conscious', 'tech enthusiast', 'gift shopper',
                                     'rugged outdoors user'])),
        })
    return personas


def persona_text(p):
    top = sorted(p['interests'].items(), key=lambda kv: -kv[1])[:3]
    likes = ', '.join(f"{c.replace('-&-', ' & ')} ({w:.0%})" for c, w in top)
    brand = f"prefers {', '.join(p['brands'])}" if p['brands'] else 'no brand loyalty'
    return (f"You own a {p['device']}. You are a {p['style']} shopper who {BUDGETS[p['budget']]}, "
            f"{brand}. Your accessory interests, by share of attention: {likes}.")


def card(i, d):
    devices = ', '.join(d.get('compatible_devices') or []) or 'universal'
    return f"{i + 1}. {d['title']} | brand: {d['manufacturer']} | {d['category']} | ${d['price']:.2f} | fits: {devices[:80]}"


class LLM:
    def __init__(self, cfg, cache_file=CACHE / 'llm_cache.jsonl'):
        from openai import AsyncOpenAI
        self.cfg = cfg; self.cache_file = cache_file; self.cache = {}
        self.client = AsyncOpenAI(max_retries=0)
        self.sem = asyncio.Semaphore(cfg['concurrency']); self.tokens = {'in': 0, 'out': 0, 'think': 0, 'calls': 0}
        if cache_file.exists():
            for line in cache_file.read_text().splitlines():
                r = json.loads(line); self.cache[r['key']] = r['response']

    async def json(self, prompt, seed):
        import openai
        key = hashlib.sha256(json.dumps([self.cfg['model'], self.cfg['temperature'], seed, prompt]).encode()).hexdigest()
        if key in self.cache:
            return self.cache[key]
        async with self.sem:
            for attempt in range(6):
                try:
                    r = await self.client.chat.completions.create(
                        model=self.cfg['model'], messages=[{'role': 'user', 'content': prompt}],
                        response_format={'type': 'json_object'}, temperature=self.cfg['temperature'], seed=seed,
                        reasoning_effort=self.cfg['reasoning_effort'])
                    parsed = json.loads(r.choices[0].message.content)
                    break
                except (openai.AuthenticationError, openai.PermissionDeniedError, openai.BadRequestError):
                    raise
                except Exception:  # rate limits, transient 5xx, malformed JSON
                    if attempt == 5:
                        raise
                    await asyncio.sleep(2 ** attempt)
        u = r.usage
        self.tokens['in'] += u.prompt_tokens; self.tokens['out'] += u.completion_tokens
        self.tokens['think'] += getattr(u.completion_tokens_details, 'reasoning_tokens', 0) or 0
        self.tokens['calls'] += 1
        self.cache[key] = parsed
        with self.cache_file.open('a') as f:
            f.write(json.dumps({'key': key, 'response': parsed}) + '\n')
        return parsed


async def isp_search(http, cfg, q, page=1, category=None):
    body = {'q': q, 'page': page, 'per_page': cfg['slate_size'], 'mode': cfg['search_mode']}
    if category:
        body['filters'] = {'category': [category]}
    r = await http.post(f"{cfg['isp_url']}/v1/indexes/{cfg['index_id']}/search/public", json=body, timeout=60)
    r.raise_for_status()
    return [h.get('document', h)['id'] for h in r.json()['hits']]


async def fetch_catalog(cfg):
    f = CACHE / 'catalog.json'
    if f.exists():
        return json.loads(f.read_text())
    docs = {}
    async with httpx.AsyncClient() as http:
        for page in range(1, 20):
            r = await http.post(f"{cfg['isp_url']}/v1/indexes/{cfg['index_id']}/search/public",
                                json={'q': '', 'page': page, 'per_page': 50}, timeout=60)
            hits = r.json()['hits']
            if not hits:
                break
            for h in hits:
                d = h.get('document', h); docs[d['id']] = d
    f.write_text(json.dumps(docs))
    return docs


async def head_pools(cfg, docs):
    """Products on pages 1..browse_pages of each category's default listing, in default order (cached)."""
    f = CACHE / 'head_pools.json'
    if f.exists():
        return json.loads(f.read_text())
    pools = {}
    async with httpx.AsyncClient(timeout=120) as http:
        for cat in sorted({d['category'] for d in docs.values()}):
            ids = []
            for page in range(1, cfg['browse_pages'] + 1):
                ids += await isp_search(http, cfg, '', page=page, category=cat)
            pools[cat] = ids
    f.write_text(json.dumps(pools, indent=1))
    return pools


async def queries_for(llm, p, n):
    prompt = (f"{persona_text(p)}\nYou will visit a mobile-accessory store {n} separate times. For each visit, "
              f"write the exact search query you would type, reflecting what you need that day. Vary the needs "
              f"according to your interests; write queries the way real shoppers type (short, sometimes vague). "
              f'Return JSON {{"queries": [{n} strings]}}.')
    out = await llm.json(prompt, seed=1000 + p['id'])
    qs = [str(q) for q in out.get('queries', [])][:n]
    return qs + ['phone accessories'] * (n - len(qs))


async def judge_clicks(llm, p, context, slate, docs, seed):
    cards = '\n'.join(card(i, docs[d]) for i, d in enumerate(slate))
    prompt = (f"{persona_text(p)}\n{context}\nThe page shows, in this order:\n{cards}\n"
              f"First decide whether any result is the kind of product you came for and fits your phone and "
              f"budget. Then list the results you would actually click to look at. Behave like a real shopper: "
              f"most people click zero to two items and pay more attention near the top; if nothing fits what "
              f"you came for, you leave without clicking. "
              f'Return JSON {{"anything_fits": true or false, "clicked": [result numbers]}}.')
    out = await llm.json(prompt, seed)
    picked = {int(x) - 1 for x in out.get('clicked', []) if str(x).lstrip('-').isdigit()}
    return [i in picked for i in range(len(slate))]


async def judge_interest(llm, p, candidates, docs, seed):
    cards = '\n'.join(card(i, docs[d]) for i, d in enumerate(candidates))
    prompt = (f"{persona_text(p)}\nYou are casually browsing the store with no search query. Rate how interested "
              f"you would be in each product: 0 = not at all, 1 = slightly, 2 = would click, 3 = would likely buy.\n"
              f'{cards}\nReturn JSON {{"ratings": [{len(candidates)} integers in listed order]}}.')
    out = await llm.json(prompt, seed)
    r = [int(x) if str(x).isdigit() else 0 for x in out.get('ratings', [])][:len(candidates)]
    return np.array(r + [0] * (len(candidates) - len(r)), float).clip(0, 3)


async def simulate(cfg, llm, docs, personas):
    rng = np.random.default_rng(cfg['session_seed'])
    ntrain = int(len(personas) * cfg['train_fraction'])
    plan = []  # fixed before any LLM call
    for step in range(cfg['train_sessions']):
        for p in personas[:ntrain]:
            search = bool(rng.random() < cfg['search_share'])
            cats, w = zip(*p['interests'].items())
            plan.append((p, step, search, str(rng.choice(cats, p=np.array(w) / sum(w))),
                         int(rng.integers(1, cfg['browse_pages'] + 1))))
    qs = await asyncio.gather(*[queries_for(llm, p, cfg['train_sessions']) for p in personas[:ntrain]])
    qs = {p['id']: q for p, q in zip(personas[:ntrain], qs)}
    rows, sessions = [], []
    head = await head_pools(cfg, docs) if cfg['browse_order'] == 'shuffled_head' else {}
    # Bounded concurrency: the ISP endpoint embeds each query, so flooding it stalls the run.
    gate = asyncio.Semaphore(cfg['concurrency'])
    async with httpx.AsyncClient(timeout=httpx.Timeout(120), limits=httpx.Limits(max_connections=cfg['concurrency'])) as http:
        async def search_retry(*args, **kw):
            for attempt in range(5):
                try:
                    return await isp_search(http, cfg, *args, **kw)
                except httpx.HTTPError:
                    if attempt == 4:
                        raise
                    await asyncio.sleep(2 ** attempt)

        async def one(p, step, search, cat, page):
            async with gate:
                if search:
                    q = qs[p['id']][step]; slate = await search_retry(q)
                    context = f'You searched the store for "{q}".'
                else:
                    q = ''
                    if cfg['browse_order'] == 'shuffled_head':
                        srng = np.random.default_rng(np.random.SeedSequence([cfg['session_seed'], p['id'], step, 7]))
                        pool = [str(x) for x in srng.permutation(head[cat])]
                        k = cfg['slate_size']; slate = pool[(page - 1) * k: page * k]
                    elif cfg['browse_order'] == 'random':
                        pool = sorted(d for d in docs if docs[d]['category'] == cat)
                        srng = np.random.default_rng(np.random.SeedSequence([cfg['session_seed'], p['id'], step]))
                        slate = [str(x) for x in srng.permutation(pool)[:cfg['slate_size']]]
                    else:
                        slate = await search_retry('', page=page, category=cat)
                    context = f"You opened the {cat.replace('-&-', ' & ')} section (page {page}) with no search query."
                clicks = await judge_clicks(llm, p, context, slate, docs, seed=p['id'] * 1000 + step) if slate else []
                return p, step, q, cat, slate, clicks

        results = []
        for i in range(0, len(plan), 200):
            results += await asyncio.gather(*[one(*x) for x in plan[i:i + 200]])
            print(f'sessions {len(results)}/{len(plan)} tokens {llm.tokens}', flush=True)
    for p, step, q, cat, slate, clicks in results:  # plan order, so row order is reproducible
        sid = f"{p['id']}:{step}"
        sessions.append({'persona': p['id'], 'step': step, 'query': q, 'browse_category': '' if q else cat,
                         'shown': len(slate), 'clicks': int(sum(clicks))})
        for rank, (doc, c) in enumerate(zip(slate, clicks)):
            e = {'doc_id': doc, 'rank': rank, 'clicked': False, 'query': q, 'user': p['id'],
                 'session': sid, 'step': step}
            rows.append(e)
            if c:
                rows.append({**e, 'clicked': True})
    # Held-out personas: graded browse interest on uniformly sampled, randomly ordered candidates.
    erng = np.random.default_rng(cfg['session_seed'] + 1); ids = sorted(docs)
    contexts = [(p, k, list(erng.choice(ids, cfg['eval_candidates'], replace=False)))
                for p in personas[ntrain:] for k in range(cfg['eval_contexts'])]
    ratings = await asyncio.gather(*[judge_interest(llm, p, c, docs, seed=900000 + p['id'] * 10 + k)
                                     for p, k, c in contexts])
    evals = [{'persona': p['id'], 'context': k, 'candidates': c, 'ratings': r.tolist()}
             for (p, k, c), r in zip(contexts, ratings)]
    return rows, sessions, evals


def ndcg10(gains, scores, k=10):
    order = np.lexsort((np.arange(len(scores)), -np.asarray(scores)))[:k]
    disc = 1 / np.log2(np.arange(k) + 2)
    ideal = np.dot(np.sort(gains)[::-1][:k], disc)
    return float(np.dot(np.asarray(gains)[order], disc) / ideal) if ideal > 0 else np.nan


# The production feature extractor derives a recency feature from the wall clock. It is constant across this
# catalog (one indexing time) but its value would otherwise depend on when the analysis runs, which shifts the
# regularized fit slightly. All Study 3 analyses therefore evaluate features at one fixed instant.
FROZEN_NOW = 1790439061 + 86400


def freeze_clock():
    import isp.services.domain.popularity_model as pm
    pm.time = type('FrozenTime', (), {'time': staticmethod(lambda: FROZEN_NOW)})


def analyze(cfg, docs, rows, evals):
    freeze_clock()
    ids = sorted(docs)
    static = dict(zip(ids, np.random.default_rng(5).normal(size=len(ids))))
    results = []
    for cond in ['full', 'sparse_browse']:
        for checkpoint in cfg['checkpoints']:
            base = [r for r in rows if r['step'] < checkpoint]
            browse = [r for r in base if r['query'] == '']
            search = [r for r in base if r['query'] != '']
            if cond == 'sparse_browse':
                srng = np.random.default_rng(checkpoint)
                sess = sorted({r['session'] for r in browse})
                keep = set(srng.choice(sess, max(1, int(len(sess) * cfg['sparse_browse_fraction'])), replace=False))
                browse = [r for r in browse if r['session'] in keep]
            pooled = browse + search
            for seed in range(cfg['matched_seeds']):
                mrng = np.random.default_rng(np.random.SeedSequence([seed, checkpoint, 884]))
                matched = [pooled[i] for i in np.sort(mrng.choice(len(pooled), len(browse), replace=False))]
                fitted = {'mixed_matched': fit_scores(docs, matched, cfg['dims'])}
                if seed == 0:
                    fitted.update({'browse': fit_scores(docs, browse, cfg['dims']),
                                   'mixed': fit_scores(docs, pooled, cfg['dims']), 'static': static})
                    formula = {}
                    for name, data in [('formula_browse', browse), ('formula_mixed', pooled)]:
                        s = dict.fromkeys(ids, 0.0)
                        for r in data:
                            s[r['doc_id']] += position_weight(r['rank']) * (1 if r['clicked'] else .1)
                        formula[name] = s
                    fitted.update(formula)
                for m, sc in fitted.items():
                    sc = sc or static
                    for e in evals:
                        results.append({'condition': cond, 'checkpoint': checkpoint, 'matched_seed': seed,
                                        'method': m, 'persona': e['persona'], 'context': e['context'],
                                        'ndcg10': ndcg10(e['ratings'], [sc[c] for c in e['candidates']]),
                                        'train_rows': len({'browse': browse, 'mixed': pooled}.get(m, matched))})
    return pd.DataFrame(results)


def paired(df, cfg):
    """Browse minus matched pooled (averaged over matched seeds), persona-cluster bootstrap."""
    out = []
    rng = np.random.default_rng(cfg['session_seed'])
    for (cond, cp), g in df.groupby(['condition', 'checkpoint']):
        b = g[g.method == 'browse'].groupby('persona').ndcg10.mean()
        for other in ['mixed_matched', 'mixed']:
            o = g[g.method == other].groupby('persona').ndcg10.mean()
            d = (b - o).dropna().to_numpy()
            boots = [rng.choice(d, len(d)).mean() for _ in range(cfg['bootstrap'])]
            lo, hi = np.percentile(boots, [2.5, 97.5])
            out.append({'condition': cond, 'checkpoint': cp, 'comparison': f'browse - {other}',
                        'delta': float(d.mean()), 'ci_low': float(lo), 'ci_high': float(hi), 'personas': len(d)})
    return pd.DataFrame(out)


def realism(rows, sessions):
    s = pd.DataFrame(sessions); s['type'] = np.where(s['query'] == '', 'browse', 'search')
    imp = pd.DataFrame([r for r in rows if not r['clicked']])
    clk = pd.DataFrame([r for r in rows if r['clicked']])
    imp['type'] = np.where(imp['query'] == '', 'browse', 'search')
    clk['type'] = np.where(clk['query'] == '', 'browse', 'search') if len(clk) else []
    ctr = (clk.groupby('type').size() / imp.groupby('type').size()).to_dict()
    pos = (clk.groupby('rank').size() / imp.groupby('rank').size()).fillna(0).round(4).to_dict()
    return {'impression_ctr': ctr, 'ctr_by_rank': pos, 'zero_click_session_share':
            s.groupby('type').clicks.apply(lambda c: float((c == 0).mean())).to_dict(),
            'clicks_per_session': s.groupby('type').clicks.mean().to_dict(),
            'distinct_queries': int(s[s.type == 'search']['query'].nunique())}


async def main(out, cfg, pilot, arm=''):
    if pilot:
        cfg = {**cfg, 'personas': 25, 'train_sessions': 5, 'checkpoints': [5], 'matched_seeds': 3,
               'bootstrap': 500}
    CACHE.mkdir(exist_ok=True); (out / 'data').mkdir(parents=True, exist_ok=True)
    start = time.time()
    docs = await fetch_catalog(cfg)
    personas = make_personas(cfg)
    llm = LLM(cfg)
    rows, sessions, evals = await simulate(cfg, llm, docs, personas)
    (CACHE / f"{arm}isp_rows.json").write_text(json.dumps(rows))
    tag = ('pilot_' if pilot else '') + arm
    df = analyze(cfg, docs, rows, evals)
    diffs = paired(df, cfg)
    summary = {'llm_tokens_this_run': llm.tokens, 'sessions': len(sessions), 'event_rows': len(rows),
               'eval_contexts': len(evals), 'realism': realism(rows, sessions),
               'runtime_seconds': time.time() - start, 'python': platform.python_version(),
               'config_sha256': hashlib.sha256(json.dumps(cfg, sort_keys=True).encode()).hexdigest(),
               'study_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}
    (out / f'data/{tag}isp_design.json').write_text(json.dumps(cfg, indent=2))
    (out / f'data/{tag}isp_personas.json').write_text(json.dumps(personas, indent=2))
    (out / f'data/{tag}isp_sessions.json').write_text(json.dumps(sessions))
    (out / f'data/{tag}isp_evals.json').write_text(json.dumps([{**e, 'candidates': [str(c) for c in e['candidates']]}
                                                              for e in evals]))
    df.to_csv(out / f'data/{tag}isp_metrics.csv', index=False)
    diffs.to_csv(out / f'data/{tag}isp_paired_differences.csv', index=False)
    (out / f'data/{tag}isp_summary.json').write_text(json.dumps(summary, indent=2, default=float))
    print(json.dumps(summary, indent=2, default=float))
    print(df.groupby(['condition', 'checkpoint', 'method']).ndcg10.mean().round(3).to_string())
    print(diffs.to_string())


if __name__ == '__main__':
    p = argparse.ArgumentParser()

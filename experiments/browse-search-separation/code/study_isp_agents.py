    a = p.parse_args()
    arm = {'default': '', 'random': 'randbrowse_', 'shuffled_head': 'shuffledhead_'}[a.browse_order]
    asyncio.run(main(a.out, {**CONFIG, 'browse_order': a.browse_order}, a.pilot, arm))
